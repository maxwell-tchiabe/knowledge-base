from __future__ import annotations

from collections.abc import Sequence

import psycopg
from pgvector import Vector
from pgvector.psycopg import register_vector
from psycopg.types.json import Jsonb

from knowledge_ingest.models import Chunk, DocumentMetadata
from knowledge_ingest.providers import EMBEDDING_DIMENSIONS

_DOCUMENTS_SCHEMA = """
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_path TEXT NOT NULL UNIQUE,
    source_url TEXT,
    sha256 CHAR(64) NOT NULL,
    page_count INTEGER NOT NULL CHECK (page_count >= 0),
    title TEXT NOT NULL,
    institution TEXT,
    publication_date DATE,
    legal_validity TEXT,
    category TEXT,
    language TEXT,
    version TEXT,
    embedding_model TEXT NOT NULL DEFAULT '',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""

_CHUNKS_SCHEMA = f"""
CREATE TABLE IF NOT EXISTS document_chunks (
    chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(document_id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL,
    page_start INTEGER NOT NULL CHECK (page_start >= 1),
    page_end INTEGER NOT NULL CHECK (page_end >= page_start),
    page_numbers INTEGER[] NOT NULL,
    section_title TEXT,
    embedding vector({EMBEDDING_DIMENSIONS}) NOT NULL,
    UNIQUE (document_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS document_chunks_embedding_hnsw
    ON document_chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX IF NOT EXISTS documents_category_idx ON documents (category);
"""


class PostgresStore:
    def __init__(self, database_url: str) -> None:
        self._database_url = database_url

    def initialize(self) -> None:
        with psycopg.connect(self._database_url) as connection:
            connection.execute("CREATE EXTENSION IF NOT EXISTS vector")
            connection.execute(_DOCUMENTS_SCHEMA)
            connection.execute(
                """
                ALTER TABLE documents
                ADD COLUMN IF NOT EXISTS embedding_model TEXT NOT NULL DEFAULT ''
                """
            )
            embedding_type = connection.execute(
                """
                SELECT format_type(attribute.atttypid, attribute.atttypmod)
                FROM pg_attribute AS attribute
                WHERE attribute.attrelid = to_regclass('document_chunks')
                  AND attribute.attname = 'embedding'
                  AND NOT attribute.attisdropped
                """
            ).fetchone()
            if embedding_type is not None and embedding_type[0] != (
                f"vector({EMBEDDING_DIMENSIONS})"
            ):
                connection.execute("DELETE FROM document_chunks")
                connection.execute(
                    "ALTER TABLE document_chunks DROP COLUMN embedding"
                )
                connection.execute(
                    f"""
                    ALTER TABLE document_chunks
                    ADD COLUMN embedding vector({EMBEDDING_DIMENSIONS}) NOT NULL
                    """
                )
                connection.execute(
                    "UPDATE documents SET embedding_model = ''"
                )
            elif embedding_type is None:
                chunks_table_exists = connection.execute(
                    "SELECT to_regclass('document_chunks') IS NOT NULL"
                ).fetchone()
                if chunks_table_exists is not None and chunks_table_exists[0]:
                    connection.execute("DELETE FROM document_chunks")
                    connection.execute(
                        f"""
                        ALTER TABLE document_chunks
                        ADD COLUMN embedding vector({EMBEDDING_DIMENSIONS}) NOT NULL
                        """
                    )
                    connection.execute("UPDATE documents SET embedding_model = ''")

            connection.execute(_CHUNKS_SCHEMA)
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS document_chunks_embedding_hnsw
                    ON document_chunks USING hnsw (embedding vector_cosine_ops)
                """
            )
            connection.execute(
                "CREATE INDEX IF NOT EXISTS documents_category_idx ON documents (category)"
            )
            register_vector(connection)

    def is_unchanged(
        self, source_path: str, sha256: str, embedding_model: str
    ) -> bool:
        with psycopg.connect(self._database_url) as connection:
            row = connection.execute(
                """
                SELECT sha256, embedding_model
                FROM documents
                WHERE source_path = %s
                """,
                (source_path,),
            ).fetchone()
        return (
            row is not None
            and row[0].strip() == sha256
            and row[1] == embedding_model
        )

    def replace_document(
        self,
        *,
        source_path: str,
        sha256: str,
        page_count: int,
        embedding_model: str,
        metadata: DocumentMetadata,
        chunks: Sequence[Chunk],
        embeddings: Sequence[Sequence[float]],
    ) -> None:
        if len(chunks) != len(embeddings):
            raise ValueError(
                f"Chunk/embedding count mismatch: {len(chunks)} chunks, "
                f"{len(embeddings)} vectors."
            )

        with psycopg.connect(self._database_url) as connection:
            register_vector(connection)
            with connection.cursor() as cursor:
                row = cursor.execute(
                    """
                    INSERT INTO documents (
                        source_path, sha256, page_count, title, institution,
                        publication_date, legal_validity, category, language,
                        version, embedding_model, metadata, updated_at
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, now())
                    ON CONFLICT (source_path) DO UPDATE SET
                        sha256 = EXCLUDED.sha256,
                        page_count = EXCLUDED.page_count,
                        title = EXCLUDED.title,
                        institution = EXCLUDED.institution,
                        publication_date = EXCLUDED.publication_date,
                        legal_validity = EXCLUDED.legal_validity,
                        category = EXCLUDED.category,
                        language = EXCLUDED.language,
                        version = EXCLUDED.version,
                        embedding_model = EXCLUDED.embedding_model,
                        metadata = EXCLUDED.metadata,
                        updated_at = now()
                    RETURNING document_id
                    """,
                    (
                        source_path,
                        sha256,
                        page_count,
                        metadata.title,
                        metadata.institution,
                        metadata.publication_date,
                        metadata.legal_validity,
                        metadata.category,
                        metadata.language,
                        metadata.version,
                        embedding_model,
                        Jsonb(metadata.as_dict()),
                    ),
                ).fetchone()
                if row is None:
                    raise RuntimeError(
                        f"Database did not return an ID for {source_path}."
                    )
                document_id = row[0]
                cursor.execute(
                    "DELETE FROM document_chunks WHERE document_id = %s",
                    (document_id,),
                )
                if chunks:
                    cursor.executemany(
                        """
                        INSERT INTO document_chunks (
                            document_id, chunk_index, content, page_start,
                            page_end, page_numbers, section_title, embedding
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                        """,
                        [
                            (
                                document_id,
                                chunk.chunk_index,
                                chunk.content,
                                min(chunk.page_numbers),
                                max(chunk.page_numbers),
                                list(chunk.page_numbers),
                                chunk.section_title,
                                Vector(list(embedding)),
                            )
                            for chunk, embedding in zip(
                                chunks, embeddings, strict=True
                            )
                        ],
                    )
